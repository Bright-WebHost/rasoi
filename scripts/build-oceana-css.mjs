// Scopes the Oceana dashboard stylesheet under `.oc` so it never leaks into the
// customer site. Source: scripts/oceana.raw.css -> app/(dashboard)/dashboard/oceana.css
import postcss from "postcss";
import { readFileSync, writeFileSync } from "node:fs";

const [src, out] = process.argv.slice(2);
const root = postcss.parse(readFileSync(src, "utf8"));
root.walkRules((rule) => {
  if (rule.parent?.type === "atrule" && /keyframes/i.test(rule.parent.name)) return;
  rule.selectors = rule.selectors.map((s) => {
    if (s === ":root" || s === "body") return ".oc";
    if (s === "*") return ".oc,.oc *";
    if (s.startsWith(".navopen")) return ".oc" + s;
    return ".oc " + s;
  });
});
root.walkDecls((d) => {
  d.value = d.value
    .replace(/Fraunces,serif/g, "var(--font-fraunces),Georgia,serif")
    .replace(/Inter,system-ui/g, "var(--font-inter),system-ui");
});
writeFileSync(out, "/* Generated by scripts/build-oceana-css.mjs — edit scripts/oceana.raw.css */\n" + root.toString());
